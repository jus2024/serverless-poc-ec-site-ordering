/**
 * 決済段階の判定（要件 4.2 / 4.3 / 4.5 / 4.8、design §5.5）。
 *
 * 決済は外部 API の呼び出しを擬似待機で置き換える（スコープ外の定義）。
 * つまり**この段階の実処理は待つことだけ**であり、判断すべきことは
 * 「意図的に失敗させるか」の 1 点しかない。その 1 点を純粋関数として切り出し、
 * 乱数の消費をハンドラ側（`stages.ts`）に残している。
 *
 * ## 失敗率を持つ理由（要件 4.8）
 *
 * 決済失敗は `PAYMENT_FAILED` の記録経路（要件 4.5 / 4.6）と、
 * **業務的な失敗を再試行しない**という約束（要件 16.7 / design §E-2）を
 * 実際に動かして確かめるための唯一の手段である。
 * 失敗率 0 のままでは、その経路が一度も実行されないままシナリオが終わる。
 *
 * ## 乱数を引数で受け取る
 *
 * `Math.random()` を内部で呼ぶと、境界（失敗率 0 と 1）の挙動を
 * 単体テストで確かめられない。乱数の生成は呼び出し側に置く。
 * 種を指定できる乱数生成器を持ち込まないのは、決済失敗の**再現性が
 * 検証の要件ではない**ためである（どの注文が失敗したかは問わない。
 * 失敗したときの経路が正しいかだけを問う）。
 */

/**
 * 擬似決済が拒否されたときの `failure_reason`（要件 4.5）。
 *
 * 「意図的な失敗である」ことを文面に含める。負荷シナリオの最中に
 * `PAYMENT_FAILED` の注文を見つけた検証者が、設定によるものか
 * 実装の不具合かを注文レコードだけで判断できるようにするためである。
 */
export const PAYMENT_DECLINED_REASON =
  '擬似決済が拒否されました（ORDER_PAYMENT_FAILURE_RATE による意図的な失敗）';

/**
 * 決済を拒否するか判定する。
 *
 * @param failureRate 失敗率（0〜1。design §10.1 の `ORDER_PAYMENT_FAILURE_RATE`）
 * @param sample 0 以上 1 未満の乱数（`Math.random()` の値）
 *
 * 失敗率 0 では**決して失敗しない**、1 では**必ず失敗する**ことを
 * 比較演算の向きだけに頼らず明示的に分岐している。`sample < failureRate` は
 * `Math.random()` の値域（`[0, 1)`）に依存した式であり、値域の異なる乱数を
 * 渡されたときに境界が崩れる。境界だけは値域と無関係に固定しておく。
 */
export function shouldDeclinePayment(failureRate: number, sample: number): boolean {
  if (!(failureRate > 0)) return false;
  if (failureRate >= 1) return true;
  return sample < failureRate;
}
